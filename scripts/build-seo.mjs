#!/usr/bin/env node
// Technical-SEO build step.
//
// Reads `seo.config.mjs` (the single source of truth for the site origin and
// public routes) and emits:
//   * a crawlable directory page per route (typing-test/, practice/, ...),
//   * a fresh `sitemap.xml`,
//   * a fresh `robots.txt`.
//
// The root `index.html` is also rewritten in place so its static <head> always
// matches the deployed origin. Run:
//
//     node scripts/build-seo.mjs
//
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { SITE_ORIGIN, SITE_NAME, ROUTES, OG_IMAGE } from "../seo.config.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TEMPLATE = join(ROOT, "index.html");

const ORIGIN = SITE_ORIGIN.replace(/\/+$/, "");

const esc = (s) =>
  String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

function absUrl(path) {
  return ORIGIN + (path === "/" ? "/" : path);
}

function seoBlock(route) {
  const url = absUrl(route.path);
  const image = ORIGIN + OG_IMAGE;
  const graph = {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "WebSite",
        name: SITE_NAME,
        url: ORIGIN + "/",
        description:
          "Free typing tests, letter drills and WPM tracking.",
        inLanguage: "en",
      },
      {
        "@type": "WebPage",
        name: route.title,
        description: route.description,
        url,
        isPartOf: { "@type": "WebSite", name: SITE_NAME, url: ORIGIN + "/" },
      },
      {
        "@type": "SoftwareApplication",
        name: SITE_NAME,
        applicationCategory: "EducationalApplication",
        operatingSystem: "Web",
        offers: { "@type": "Offer", price: "0", priceCurrency: "USD" },
      },
    ],
  };

  return [
    `  <!-- seo:start (generated by scripts/build-seo.mjs — do not edit by hand) -->`,
    `  <title>${esc(route.title)}</title>`,
    `  <meta name="description" content="${esc(route.description)}">`,
    `  <meta name="keywords" content="typing test, free typing test, WPM test, typing speed test, typing practice, keyboard practice, words per minute, typing accuracy">`,
    `  <meta name="author" content="${esc(SITE_NAME)}">`,
    `  <meta name="robots" content="index, follow">`,
    `  <meta name="theme-color" content="#2f6bff">`,
    `  <link rel="canonical" href="${url}" id="canonicalLink">`,
    `  <link rel="alternate" hreflang="en" href="${url}">`,
    `  <link rel="alternate" hreflang="x-default" href="${url}">`,
    `  <meta property="og:type" content="website">`,
    `  <meta property="og:site_name" content="${esc(SITE_NAME)}">`,
    `  <meta property="og:locale" content="en_US">`,
    `  <meta property="og:title" content="${esc(route.title)}" id="ogTitle">`,
    `  <meta property="og:description" content="${esc(route.description)}" id="ogDesc">`,
    `  <meta property="og:url" content="${url}" id="ogUrl">`,
    `  <meta property="og:image" content="${image}" id="ogImage">`,
    `  <meta property="og:image:width" content="1200">`,
    `  <meta property="og:image:height" content="630">`,
    `  <meta name="twitter:card" content="summary_large_image">`,
    `  <meta name="twitter:title" content="${esc(route.title)}" id="twTitle">`,
    `  <meta name="twitter:description" content="${esc(route.description)}" id="twDesc">`,
    `  <meta name="twitter:image" content="${image}" id="twImage">`,
    `  <script type="application/ld+json" id="ldJson">${JSON.stringify(graph)}</script>`,
    `  <!-- seo:end -->`,
  ].join("\n");
}

function routeBlock(route) {
  const boot = `window.__SITE_ORIGIN__ = ${JSON.stringify(ORIGIN)}; window.__ROUTE__ = ${JSON.stringify(route.view)};`;
  return [
    `  <!-- route:start (generated by scripts/build-seo.mjs) -->`,
    `  <script>${boot}</script>`,
    `  <!-- route:end -->`,
  ].join("\n");
}

function render(template, route) {
  let html = template.replace(
    /[ \t]*<!-- seo:start[\s\S]*?<!-- seo:end -->/,
    seoBlock(route),
  );
  html = html.replace(
    /[ \t]*<!-- route:start[\s\S]*?<!-- route:end -->/,
    routeBlock(route),
  );
  return html;
}

function buildSitemap(routes) {
  const entries = routes
    .filter((r) => r.inSitemap !== false)
    .map((r) => {
      const lines = [
        `  <url>`,
        `    <loc>${absUrl(r.path)}</loc>`,
        `    <changefreq>${r.changefreq || "monthly"}</changefreq>`,
        `    <priority>${r.priority || "0.5"}</priority>`,
        `  </url>`,
      ];
      return lines.join("\n");
    })
    .join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries}\n</urlset>\n`;
}

function buildRobots() {
  return `User-agent: *\nAllow: /\n\nSitemap: ${ORIGIN}/sitemap.xml\n`;
}

function main() {
  const template = readFileSync(TEMPLATE, "utf8");
  if (!/<!-- seo:start/.test(template) || !/<!-- route:start/.test(template)) {
    throw new Error("index.html is missing the seo:start / route:start markers.");
  }

  for (const route of ROUTES) {
    const html = render(template, route);
    const out = join(ROOT, route.out);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, html, "utf8");
    console.log(`route  ${route.path} -> ${route.out}`);
  }

  writeFileSync(join(ROOT, "sitemap.xml"), buildSitemap(ROUTES), "utf8");
  console.log("wrote  sitemap.xml");
  writeFileSync(join(ROOT, "robots.txt"), buildRobots(), "utf8");
  console.log("wrote  robots.txt");
}

main();
